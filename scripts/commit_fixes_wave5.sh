fix(untar): create each directory once instead of re-walking its ancestors per entry

Deep extraction scaled super-linearly with depth (#16). Measured, not read:

`extract_entries` called `fs::create_dir_all(parent)` on every entry, and again on the target for
every Directory entry, with no memory of what it had already created. On an existing path
`create_dir_all` does mkdir() (EEXIST) and then is_dir() (a stat), and each of those resolves
every component of the path -- so a tree d levels deep with n entries below it paid n*d full path
resolutions. The agent's instrumented counter makes it exact: ancestor-component work at
d=100/200/400 was 11909/43809/167609, ratios 3.68x and 3.83x for a 2x depth step, i.e. Theta(d^2).

Fix: track known-existing directories in a `HashSet<PathBuf>` and create each exactly once.

    depth=200 files=2000   before 395.19ms  dir_calls=2400
                           after  352.89ms  dir_calls=201

`dir_calls` is deterministic (the wall clock on this device is noisy at +/-30%); it drops from
2 per directory entry to 1, and from 2400 to 201 on that shape -- 11.9x fewer, and now
proportional to distinct directories rather than to entries. On the entry-heavy instrumented
profile (depth 200, 5000 files) the directory term went 689ms -> 316ms, 43% -> 28% of the run.

Semantics untouched: hard-link-first-then-copy (SELinux), symlink recreation, special-file skip,
mode applied after content, and both security checks (`..` rejection and outside-dest rejection)
are byte-identical. Every existing test kept and passing.

The regression test asserts a **work count**, never a duration, so it cannot flake:
`deep_tree_creates_each_directory_once` asserts `calls <= DEPTH + 2` for a 150-level chain with
400 files. With memoisation disabled it fails with
"700 create_dir_all calls for 400 files under 150 levels: the ancestor chain is walked once per
entry, not once per directory"; with the fix it is 150.

Honest limit, recorded because it matters: the reported "150 levels -> 50s" is NOT reproducible on
this hardware from a plain chain (a 400-level chain is ~330ms), so the absolute magnitudes in the
issue came from a different shape or environment. What is reproducible is the quadratic directory
work above, and it dominates (43%) on entry-heavy deep archives -- which is the shape a real
200+ level layer has. The residual per-entry cost (File::create/io::copy/chmod/is_inside) is
intrinsic to a path-based API and would need openat-relative operations in dirfd.rs, not this file.

Closes #16
EOF

