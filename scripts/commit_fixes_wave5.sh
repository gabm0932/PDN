fix(copy): keep sparse files sparse instead of densifying them

`podnext copy` and `podnext sync` used `std::fs::copy`. On Android/aarch64 its `copy_file_range`
fast path is unavailable, so std degenerates to a buffered read/write loop that transfers every
logical byte and never asks the filesystem where the holes are. Measured on a 1 GiB sparse source
holding 16 KiB of real data:

    source          1073741824 bytes,     32 blocks  (du -B1: 16384)
    before (copy)   1073741824 bytes, 2099216 blocks  (du -B1: 1074798592)  -> densified
    after  (copy)   1073741824 bytes,     32 blocks   (du -B1: 16384)       -> preserved

`copy_preserving_holes` walks the source with `lseek(SEEK_DATA)`/`lseek(SEEK_HOLE)`, reads and
writes only allocated regions, seeks the output to each data offset, and fixes the final length
with `set_len`, so gaps stay holes and a trailing hole extends correctly. All three call sites
routed through it (single-file `cmd_copy`, `sync_one`, `copy_dir_recursive`).

Correctness guarded, not assumed:

- non-sparse content is byte-identical: 5 MiB of urandom, `cmp` equal and equal `sha256`
  (24684019c97c33a46a0ea8ce49fdba7ff02d036c9afb1d778fee83d90d58ba30), blocks 10248 before/after
- a longer destination (2 GiB) is shrunk to the source size, holes intact
- a shorter destination (1 KiB) is extended correctly
- an empty file stays 0 bytes / 0 blocks
- permissions are copied from the source
- on any read/write error the partial destination is removed before returning, matching
  `std::fs::copy`, so a silently truncated file is never left behind
- if `SEEK_DATA` is unsupported (EINVAL/ENOTSUP) it falls back to the previous dense path rather
  than failing

`SEEK_DATA`/`SEEK_HOLE` are supported on this kernel, verified directly rather than assumed
(`lseek` -> 1048576 for the first data offset on the sparse fixture).

Test `tests::copy_keeps_sparse_files_sparse` builds a 64 MiB file with one 4 KiB page, copies it,
asserts apparent size, byte-identity, and that allocated blocks stay under 1 MiB -- with a
skip-guard if the test filesystem itself lacks hole support.

Closes #18
EOF

