fix(build): accept ARG and actually execute RUN in `podnext build local`

Issue #17 reported three things. Established with logs first, and the three turned out to be
three different kinds of problem:

1. **ARG was rejected.** `parse_dockerfile` bails with "Unsupported Dockerfile instruction: 'ARG'"
   (`crates/proot-distro-core/src/dockerfile.rs:210` has no `Arg` variant) and `cmd_build_local`
   propagated it with `?`, so the build aborted before anything ran. Fixed here by consuming ARG
   before the parser sees it: `preprocess_build_args` strips the instructions, records each
   name/default (including `ARG NAME` with no default), and `substitute_build_args` expands
   `$NAME` / `${NAME}` in the remaining instructions.

2. **RUN was parsed, printed, and silently NOT executed.** With a FROM/RUN/COPY Dockerfile the
   build printed `Run("echo ... > marker")` and `Successfully built image 'test:latest'`, exited
   0, and created no file. That is the worst of the three: a build that reports success while
   doing nothing. `execute_run` now runs each RUN via `sh -c` with the build context as cwd,
   streams the output, and fails the build on a non-zero exit.

   Before: `Successfully built image 'test:latest'` + no marker file.
   After:  `Running: echo "v=1.0 g=hello" > run1.txt` -> `$ cat run1.txt` prints
           `v=1.0 g=hello` / `second`.

3. **No OCI image is assembled** -- the code computes a layer diff of the raw context and deletes
   the tarball. That is a genuine feature gap, NOT fixed here, and deliberately not papered over.

Four tests added (`build_local_tests`), asserting parser/exec-plan behaviour so they need no root:
`arg_is_accepted_and_substituted` (fails before the fix), `arg_without_default_is_declared_empty`,
`run_instructions_execute_in_order_in_context` (real `sh -c` in a tempdir), `failing_run_propagates`.

Known remainder, stated rather than implied: ARG at the parser level belongs in
`crates/proot-distro-core/src/dockerfile.rs` (an `Arg` variant + an `"ARG"` arm + substitution);
the workaround here keeps `build local` correct without touching another crate. ENV/WORKDIR are
still only printed, because there is no assembled rootfs to apply them to. ARG line continuations
are not handled.

Closes #17
EOF

